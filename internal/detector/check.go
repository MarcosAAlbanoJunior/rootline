package detector

import (
	"fmt"
	"strings"

	"github.com/MarcosAAlbanoJunior/rootline/internal/trace"
)

// Check statuses: the detector ran, could not run, or does not apply to the analyzed traces.
const (
	CheckRan           = "ran"
	CheckSkipped       = "skipped"
	CheckNotApplicable = "not_applicable"
)

// Check is what one detector reports about its own run (ADR-0027): whether it ran, the observed
// fact behind that and what the user can do next.
type Check struct {
	ID, Status, Reason, Hint string
}

// hintNoQuerySpans is shared by the detectors that read query spans.
const hintNoQuerySpans = "Rootline recognizes database spans that carry db.query.text (PostgreSQL through pgx in v1); see the db_spans check and docs/guia-instrumentacao.md."

// NPlusOneCheck reports the N+1 detector run over traces, given what Detect returned.
func NPlusOneCheck(traces [][]trace.Span, cands []Candidate, discarded []Discarded) Check {
	c := Check{ID: TypeNPlusOne}
	if len(traces) == 0 {
		c.Status, c.Reason = CheckNotApplicable, "no traces of the operation in the bad version"
		return c
	}
	if countQuerySpans(traces) == 0 {
		c.Status = CheckSkipped
		c.Reason = fmt.Sprintf("no database query spans in the %d analyzed traces", len(traces))
		c.Hint = hintNoQuerySpans
		return c
	}
	c.Status = CheckRan
	var b strings.Builder
	if len(cands) == 0 {
		fmt.Fprintf(&b, "no query repeated at least %d times under one parent in at least %d traces and %.0f%% of the %d traces",
			MinRepetitions, MinAffectedTraces, MinAffectedRatio*100, len(traces))
	} else {
		fmt.Fprintf(&b, "%d candidate(s) in %d traces", len(cands), len(traces))
	}
	if len(discarded) > 0 {
		fmt.Fprintf(&b, "; %d query(ies) discarded as pagination", len(discarded))
	}
	c.Reason = b.String()
	return c
}

// hintNoPlans says, honestly, where execution plans come from today.
const hintNoPlans = "Execution plans are only generated by the evaluation today (rootline-eval record writes plans.jsonl, passed with --plans); capturing them against a test database is on the roadmap."

// MissingIndexCheck reports the missing-index detector run over traces. planned says whether plans
// were given; cands and skipped are what DetectMissingIndex returned.
func MissingIndexCheck(traces [][]trace.Span, planned bool, cands []Candidate, skipped []Skipped) Check {
	c := Check{ID: TypeMissingIndex}
	switch {
	case len(traces) == 0:
		c.Status, c.Reason = CheckNotApplicable, "no traces of the operation in the bad version"
		return c
	case countQuerySpans(traces) == 0:
		c.Status = CheckSkipped
		c.Reason = fmt.Sprintf("no database query spans in the %d analyzed traces", len(traces))
		c.Hint = hintNoQuerySpans
		return c
	case !planned:
		c.Status, c.Reason, c.Hint = CheckSkipped, "no query plans", hintNoPlans
		return c
	}
	c.Status = CheckRan
	var b strings.Builder
	if len(cands) == 0 {
		b.WriteString("no plan scans a large table sequentially through a selective filter")
	} else {
		fmt.Fprintf(&b, "%d candidate(s)", len(cands))
	}
	if len(skipped) > 0 {
		fmt.Fprintf(&b, "; %d query(ies) not judged:", len(skipped))
		for _, s := range skipped {
			fmt.Fprintf(&b, " %s: %s;", s.Query, s.Reason)
		}
		c.Hint = "Queries without a plan could not be judged; record their plans at the bad version."
	}
	c.Reason = strings.TrimSuffix(b.String(), ";")
	return c
}

func countQuerySpans(traces [][]trace.Span) int {
	n := 0
	for _, spans := range traces {
		for _, s := range spans {
			if PhaseOf(s) == PhaseQuery {
				n++
			}
		}
	}
	return n
}
